import assert from 'node:assert/strict';
import { buildActivityGraph, eventRoute, GRAPH_LIMIT } from '../src/lib/activity-graph.ts';
const event = (key, extra={}) => ({key,source:'agent',actorId:null,actor:'Agente',agentId:'a',responsibleId:'p',responsible:'Persona',entity:'item',action:'query_records',status:'completed',timestamp:`2026-09-05T12:00:${String(Number(key)||0).padStart(2,'0')}Z`,timeLabel:'fecha',duration:25,...extra});
assert.equal(buildActivityGraph([],{}).nodes.length,0);
assert.deepEqual(eventRoute(event('1')),['person:p','agent:a','core','entity:item']);
assert.deepEqual(eventRoute(event('1',{responsibleId:null})),['agent:a','core','entity:item']);
assert.deepEqual(eventRoute(event('1',{source:'human',actorId:'h',entity:null})),['person:h','core','entity:system']);
const input=[event('1'),event('2',{status:'failed'})];
const graph=buildActivityGraph(input,{item:'Elementos'});
assert.equal(graph.events.length,2);assert.equal(graph.failures,1);
assert.equal(graph.nodes.find(n=>n.key==='entity:item').label,'Elementos');
assert.equal(graph.nodes.find(n=>n.key==='agent:a').failures,1);
assert.equal(graph.edges.length,3);
assert.equal(buildActivityGraph([...input,input[0]],{}).events.length,2);
assert.equal(buildActivityGraph([event('1'),event('2',{agentId:'b'})],{}).counts.agent,2);
assert.equal(buildActivityGraph([event('1',{agentId:null}),event('2',{agentId:null})],{}).counts.agent,2);
const many=buildActivityGraph(Array.from({length:60},(_,i)=>event(String(i),{agentId:`a${i}`,entity:`item${i}`})),{});
assert.equal(many.events.length,GRAPH_LIMIT);assert.ok(many.hidden>0);
const keys=new Set(['core',...many.nodes.map(n=>n.key)]);
assert.ok(many.edges.every(e=>keys.has(e.from)&&keys.has(e.to)));
assert.deepEqual(buildActivityGraph([...input].reverse(),{}),buildActivityGraph(input,{}));
assert.equal(input[0].key,'1');
console.log('Activity graph: 15 assertions passed (bounded, deterministic, attributed, no invented owners).');
